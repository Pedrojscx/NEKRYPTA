// The backend names the weather condition from the WMO code in English; the fixed set is translated here.
function weatherCondition(label) {
    const key = "weather." + label;
    const text = t(key);
    return text === key ? label : text;
}
function t(key, args) {
    const own = catalogs[locale] || {};
    let text = key in own ? own[key] : key in catalogs.en ? catalogs.en[key] : key;
    for (const name in args || {})
        text = text.split("{" + name + "}").join(String(args[name]));
    return text;
}

// The Qt locale the interface speaks; dates, day names and numbers follow it rather than the system's.
function qtLocale() {
    return Qt.locale(locale);
}

// Qt.formatDateTime with this locale's month and day names. Numeric formats ("yyyy-MM-dd") come out the same.
function date(value, format) {
    const when = value instanceof Date ? value : new Date(value);
    return qtLocale().toString(when, format === undefined ? Locale.ShortFormat : format);
}

// The full date in this locale's own long form: "terça-feira, 20 de outubro de 2026" in pt_BR.
function longDate(value) {
    const when = value instanceof Date ? value : new Date(value);
    const locale = qtLocale();
    // 0 is Locale.LongFormat; the Locale enum is not visible inside a .pragma library script.
    return locale.toString(when, locale.dateFormat(0));
}

// A number with this locale's separators ("1,5" in pt_BR).
function number(value, decimals) {
    return Number(value).toLocaleString(qtLocale(), "f", decimals || 0);
}

// A backend error ({code, message}) in this locale: the message for its code (docs/architecture/error-codes.md),
// or the backend's own English message for codes without one.
function error(failure) {
    if (!failure)
        return "";
    const key = "error." + failure.code;
    const own = catalogs[locale] || {};
    return key in own ? own[key] : failure.message || t("error.failed");
}
